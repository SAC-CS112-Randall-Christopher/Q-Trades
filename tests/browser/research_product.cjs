    await retained.getByRole("button", { name: "Fund reviewed prospective paper pair", exact: true }).click();
    await retained.getByText("The original admission is confirmed. The same prospective pair continues; no duplicate funding was created.").waitFor();
    const funded = await probe();
    const candidate = Object.entries(funded.accounts).find(([n, a]) => a.qualification_source?.trial_id === trial.id && a.campaign_id === "forward-research");
    assert(candidate); const candidateName = candidate[0];

    const nextLink = page.locator(`a[href="#research?task=${reopened.successor}"]`).first();
    await nextLink.click(); await page.waitForURL(`**/#research?task=${reopened.successor}`);
    await page.goBack(); await page.waitForURL(`**/#research?task=${original}`);
    await page.getByRole("heading", { name: "Recorded comparison: low_information" }).waitFor();
    await page.screenshot({ path: path.join(directory, "investigation-result-desktop.png"), fullPage: true });

    assert(requests.filter(r => r.path === "/api/research/overview").length > pollBefore);
    await page.screenshot({ path: path.join(directory, "overview-waiting-desktop.png"), fullPage: true });
    await qa("mature");
    const done = await until(p => p.tasks.some(t => t.id === original && t.status === "done"), "mature outcome and lesson", 25000);
    assert.equal(done.software_callbacks, 3);
    groups.push("automatic actual worker/preparation/evaluation/review/inbox/native funding, waiting overview, unsuppressed polling and independent financial ticks");
    phase = "original result and archive/restart continuation";
    await qa("archive-restart-successor");
